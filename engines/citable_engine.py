"""Citable answer artifacts — the GEO/attribution-proofing layer (2026).

The attribution truth: share links get pasted into ChatGPT/Slack/CRM; the
human never visits your domain; classic analytics show nothing. The 2026
answer is to make every export both human-readable (PDF) and machine-citable
(markdown twin + JSON-LD). When a model quotes your number, it quotes your
canonical URL with it, and the provenance badge survives the citation.

This engine builds:
- `markdown_twin()`  — identical content as the PDF, in a model-citable
  markdown format: H1, answer capsule (first 50 words), number table with
  per-row badge + as_of + source_url, Q&A block, canonical URL footer.
- `jsonld_dataset()` — schema.org Dataset + DataCatalog JSON-LD so the
  page is indexable with proper provenance metadata.
- `citation_block()` — the canonical citation string a model should emit.

All three share one canonical URL + estimate_id so attribution is stable.
"""

from datetime import datetime, timezone
from typing import Any

_BADGE_LEGEND = (
    "| Badge | Meaning |\n"
    "|---|---|\n"
    "| VERIFIED | Live government data (Census · BLS · FEMA · USGS · CPSC · FRED) |\n"
    "| USER_PROVIDED | Your quotes/MLS/uploads — authoritative |\n"
    "| MODELED | Deterministic estimate from verified baselines — **not a quote** |\n"
    "| REQUIRES_KEY | Live enrichment available once an API key is configured |\n"
    "| UNAVAILABLE | Source unreachable — reported honestly, never guessed |\n"
)


def canonical_url(base_url: str, estimate_id: str) -> str:
    return f"{(base_url or 'https://example.com').rstrip('/')}/e/{estimate_id}"


def markdown_twin(
    estimate_id: str,
    totals: dict,
    line_items: list[dict],
    address_hint: str = "",
    base_url: str = "",
    zip_code: str = "",
    state: str = "",
    deep_analysis: dict | None = None,
) -> str:
    """Model-citable markdown twin of the estimate. Same numbers as the PDF."""
    now = datetime.now(timezone.utc).isoformat()
    url = canonical_url(base_url, estimate_id)
    total_avg = totals.get("total_avg", 0)
    total_low = totals.get("total_low", 0)
    total_high = totals.get("total_high", 0)
    loc = f"{zip_code or state or address_hint or 'the subject property'}"
    lines = [
        f"# Repair Cost Estimate — {loc} ({estimate_id})",
        "",
        f"> **Answer:** Total repair estimate for {loc} averages **${total_avg:,.0f}** "
        f"(range ${total_low:,.0f}–${total_high:,.0f}) based on a verified cost matrix "
        f"of BLS wages and PPI materials. This is a deterministic estimate, not a quote.",
        "",
        f"*Generated {now} · config_version tracked · estimate_id `{estimate_id}`*",
        "",
        "## Cost table",
        "",
        "| Item | System | Severity | Low | Mid | High | Badge | As of | Source |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for it in (line_items or [])[:50]:
        lines.append(
            "| {desc} | {sys} | {sev} | ${lo:,.0f} | ${mid:,.0f} | ${hi:,.0f} | {badge} | {as_of} | {src} |".format(
                desc=str(it.get("finding", it.get("description", "")))[:60].replace("|", "/"),
                sys=str(it.get("system", ""))[:20],
                sev=str(it.get("severity", "")),
                lo=it.get("total_low", 0),
                mid=it.get("total_avg", 0),
                hi=it.get("total_high", 0),
                badge=it.get("badge", "MODELED"),
                as_of=str(it.get("as_of", now))[:10],
                src=str(it.get("source_url", ""))[:60],
            )
        )
    lines += [
        "",
        "## Provenance badge legend",
        "",
        _BADGE_LEGEND,
        "",
        "## Q&A",
        "",
        f"**Q: How much does repair cost in {loc} in {datetime.now().year}?**  ",
        f"A: The provenance-tracked estimate averages ${total_avg:,.0f} "
        f"(${total_low:,.0f}–${total_high:,.0f}). MODELED from BLS OEWS wages and BLS PPI "
        "materials — not a contractor quote. USER_PROVIDED quotes always win.",
        "",
        "**Q: Is this estimate reliable?**  ",
        "A: Every figure carries exactly one badge (VERIFIED / USER_PROVIDED / MODELED / "
        "REQUIRES_KEY / UNAVAILABLE). Nothing is fabricated; UNAVAILABLE is reported honestly. "
        "The pipeline is deterministic: same inputs produce same outputs.",
        "",
        "## Citation",
        "",
        f"```text\n{citation_block(estimate_id, totals, base_url, loc)}\n```",
        "",
        "---",
        f"Canonical URL: {url} · Generated by Repair Estimator (deterministic, provenance-tracked)",
    ]
    if deep_analysis:
        lines += ["", "## Deep analysis excerpt", ""]
        for key, val in list(deep_analysis.items())[:5]:
            if isinstance(val, str):
                lines.append(f"- **{key}**: {val[:300]}")
            elif isinstance(val, dict) and "note" in val:
                lines.append(f"- **{key}**: {str(val['note'])[:300]}")
    return "\n".join(lines)


def jsonld_dataset(
    estimate_id: str,
    totals: dict,
    base_url: str = "",
    zip_code: str = "",
    state: str = "",
) -> dict:
    """schema.org Dataset + DataCatalog JSON-LD for the citable page."""
    now = datetime.now(timezone.utc)
    url = canonical_url(base_url, estimate_id)
    return {
        "@context": "https://schema.org",
        "@type": "Dataset",
        "name": f"Repair Cost Estimate — {zip_code or state or 'property'} ({estimate_id})",
        "description": (
            "Deterministic, provenance-tracked repair cost estimate. Every figure badged "
            "VERIFIED/USER_PROVIDED/MODELED/REQUIRES_KEY/UNAVAILABLE. Not a quote."
        ),
        "url": url,
        "identifier": estimate_id,
        "datePublished": now.isoformat(),
        "dateModified": now.isoformat(),
        "license": "https://opensource.org/licenses/MIT",
        "creator": {
            "@type": "Organization",
            "name": "Repair Estimator",
            "url": (base_url or "https://example.com").rstrip("/"),
        },
        "isAccessibleForFree": True,
        "keywords": "repair cost estimate, home inspection, provenance, BLS, deterministic",
        "measurementTechnique": "Deterministic cost matrix from BLS OEWS + PPI + versioned config",
        "variableMeasured": [
            {
                "@type": "PropertyValue",
                "name": "total_avg",
                "value": totals.get("total_avg", 0),
                "unitText": "USD",
            },
            {
                "@type": "PropertyValue",
                "name": "total_low",
                "value": totals.get("total_low", 0),
                "unitText": "USD",
            },
            {
                "@type": "PropertyValue",
                "name": "total_high",
                "value": totals.get("total_high", 0),
                "unitText": "USD",
            },
        ],
    }


def citation_block(estimate_id: str, totals: dict, base_url: str, location: str) -> str:
    """The exact string a model should emit when citing this estimate."""
    url = canonical_url(base_url, estimate_id)
    return (
        f'Repair Estimator, "Repair Cost Estimate — {location}", estimate {estimate_id}. '
        f"Total avg ${totals.get('total_avg', 0):,.0f} (range ${totals.get('total_low', 0):,.0f}–"
        f"${totals.get('total_high', 0):,.0f}), MODELED from BLS OEWS/PPI. "
        f"{datetime.now(timezone.utc).date().isoformat()}. {url}"
    )


def build_citable_package(
    estimate_id: str,
    totals: dict,
    line_items: list[dict],
    base_url: str = "",
    zip_code: str = "",
    state: str = "",
    deep_analysis: dict | None = None,
) -> dict[str, Any]:
    """Bundle markdown twin + JSON-LD + citation string for export."""
    md = markdown_twin(
        estimate_id,
        totals,
        line_items,
        base_url=base_url,
        zip_code=zip_code,
        state=state,
        deep_analysis=deep_analysis,
    )
    jsonld = jsonld_dataset(estimate_id, totals, base_url=base_url, zip_code=zip_code, state=state)
    cite = citation_block(estimate_id, totals, base_url, zip_code or state or "property")
    return {
        "markdown": md,
        "jsonld": jsonld,
        "citation": cite,
        "canonical_url": canonical_url(base_url, estimate_id),
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }
